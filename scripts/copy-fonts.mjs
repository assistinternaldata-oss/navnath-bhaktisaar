// Copies the two typefaces (SIL Open Font License) from @fontsource into fonts/, so the
// website and the apps don't depend on Google Fonts and look right offline from the start.
// Run after updating the @fontsource packages:  node scripts/copy-fonts.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'fonts');
mkdirSync(out, { recursive: true });

const wanted = [
  ['tiro-devanagari-marathi', ['400']],
  ['mukta', ['400', '500', '600', '700']],
];
const subsets = ['devanagari', 'latin'];
let css = '/* Generated by scripts/copy-fonts.mjs from @fontsource (SIL Open Font License 1.1) */\n';

for (const [pkg, weights] of wanted) {
  const dir = join(root, 'node_modules', '@fontsource', pkg);
  for (const w of weights) {
    const source = readFileSync(join(dir, `${w}.css`), 'utf8');
    for (const block of source.split('@font-face').slice(1)) {
      const name = block.match(/files\/([\w-]+)\.woff2/)?.[1];
      if (!name || !subsets.some((s) => name.includes(`-${s}-${w}-normal`))) continue;
      copyFileSync(join(dir, 'files', `${name}.woff2`), join(out, `${name}.woff2`));
      const family = block.match(/font-family:\s*'([^']+)'/)[1];
      const range = block.match(/unicode-range:\s*([^;]+);/)[1];
      css += `@font-face{font-family:'${family}';font-style:normal;font-weight:${w};font-display:swap;src:url(${name}.woff2) format('woff2');unicode-range:${range}}\n`;
    }
  }
}
writeFileSync(join(out, 'fonts.css'), css);
console.log(css.split('\n').length - 2, 'font faces written to fonts/');
